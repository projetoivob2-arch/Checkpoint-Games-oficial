create table if not exists public.site_content (
  id integer primary key check (id = 1),
  payload jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now()
);

create table if not exists public.spotlight_games (
  game_index integer primary key check (game_index between 0 and 2),
  image_url text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.opinions (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) <= 80),
  email text not null check (char_length(email) <= 120),
  message text not null check (char_length(message) between 1 and 3000),
  created_at timestamptz not null default now(),
  status text not null default 'pendente' check (status in ('pendente','aprovada','arquivada'))
);

alter table public.site_content enable row level security;
alter table public.spotlight_games enable row level security;
alter table public.opinions enable row level security;

